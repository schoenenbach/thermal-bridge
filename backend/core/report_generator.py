def generate_pdf_report(project_name, author, description, results, image_path, output_path):
    """
    Generates a PDF report from simulation results.
    """
    
    import base64
    from io import BytesIO

    img_src = ""
    if image_path:
        if isinstance(image_path, str) and os.path.exists(image_path):
             img_src = f"file://{os.path.abspath(image_path)}"
        elif hasattr(image_path, 'read') or isinstance(image_path, bytes):
             # It's a buffer or bytes
             if hasattr(image_path, 'read'):
                 if hasattr(image_path, 'seek'): image_path.seek(0)
                 data = image_path.read()
             else:
                 data = image_path
             b64_data = base64.b64encode(data).decode('utf-8')
             img_src = f"data:image/png;base64,{b64_data}"
    
    # 1. Prepare Context
    context = {
        "project_name": project_name,
        "author": author,
        "date": datetime.now().strftime("%Y-%m-%d %H:%M"),
        "description": description,
        "results": results,
        "image_src": img_src
    }
    
    # 2. Render HTML
    template = Template(HTML_TEMPLATE)
    html_content = template.render(context)
    
    # 3. Write PDF
    try:
        HTML(string=html_content).write_pdf(output_path)
        return True, "Report generated successfully."
    except Exception as e:
        return False, f"Failed to generate report: {str(e)}"

